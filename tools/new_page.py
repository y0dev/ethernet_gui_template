"""Create a new page as a plugin and enable it in project.json.

    python tools/new_page.py calibration "Calibration"
    python tools/new_page.py calibration "Calibration" --no-enable

Writes plugins/<key>.py with a working page (header, a button, a table, a
named-query call) and adds it to project.json -> plugins and pages.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

TEMPLATE = '''"""{title} page (plugin).

Generated by tools/new_page.py.  Everything the application offers is on
``ctx`` (app/context.py): ``ctx.db`` (``ctx.db.run("query.name", ...)`` for
queries in sql/*.sql), ``ctx.workflow``, ``ctx.connections``, ``ctx.capture``,
``ctx.devices``, ``ctx.operations``, ``ctx.config`` ...
Keep logic in a service or function you can test without the GUI.
"""

from __future__ import annotations

from PySide6.QtWidgets import QLabel, QPushButton, QTableWidget, QTableWidgetItem, QVBoxLayout, QWidget

from app.ui.widgets.common import PageHeader, configure_table


class {cls}(QWidget):
    def __init__(self, ctx, parent: QWidget | None = None) -> None:
        \"\"\"Build the page header, refresh button and result table.

        Args:
            ctx: Application context with every service.
            parent: Optional parent widget.
        \"\"\"
        super().__init__(parent)
        self.ctx = ctx
        layout = QVBoxLayout(self)
        layout.setContentsMargins(18, 14, 18, 14)
        header = PageHeader("{title}", "Describe what this page is for.")
        refresh = QPushButton("Refresh")
        refresh.setObjectName("Primary")
        refresh.clicked.connect(self.refresh)
        header.actions.addWidget(refresh)
        layout.addWidget(header)
        self.table = QTableWidget()
        configure_table(self.table)
        layout.addWidget(self.table, 1)
        self.status = QLabel("")
        self.status.setObjectName("Dim")
        layout.addWidget(self.status)

    def refresh(self) -> None:
        \"\"\"Reload the table from a named query.\"\"\"
        # Example: a built-in named query. Add your own in sql/*.sql.
        rows = self.ctx.db.run("sessions.list_with_counts")
        headers = ["id", "name", "packet_count"]
        self.table.setColumnCount(len(headers))
        self.table.setHorizontalHeaderLabels(headers)
        self.table.setRowCount(len(rows))
        for r, row in enumerate(rows):
            for c, key in enumerate(headers):
                self.table.setItem(r, c, QTableWidgetItem(str(row[key])))
        self.status.setText(f"{{len(rows)}} session(s)")

    def showEvent(self, event) -> None:  # noqa: N802
        \"\"\"Refresh the table whenever the page becomes visible.

        Args:
            event: Qt show event.
        \"\"\"
        super().showEvent(event)
        self.refresh()


def register(registry) -> None:
    \"\"\"Plugin entry point: add this page to the registry.

    Args:
        registry: Page registry to add the page to.
    \"\"\"
    registry.add_page("{key}", "{title}", {cls}, description="{title}")
'''


def main() -> int:
    """Generate a plugin page and optionally enable it in ``project.json``.

    The page is inserted before ``settings`` in the page list when one
    exists.

    Returns:
        The process exit code: 0 on success, 2 for an invalid key or an
        existing file.
    """
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("key", help="page key (identifier, e.g. calibration)")
    parser.add_argument("title", help="navigation title")
    parser.add_argument("--no-enable", action="store_true", help="do not edit project.json")
    parser.add_argument("--root", default=str(ROOT), help=argparse.SUPPRESS)
    args = parser.parse_args()
    root = Path(args.root)
    if not args.key.isidentifier():
        print(f"error: key {args.key!r} must be an identifier (letters, digits, underscore)")
        return 2
    target = root / "plugins" / f"{args.key}.py"
    if target.exists():
        print(f"error: {target} already exists")
        return 2
    cls = "".join(part.capitalize() for part in args.key.split("_")) + "Page"
    target.parent.mkdir(exist_ok=True)
    (target.parent / "__init__.py").touch()
    target.write_text(TEMPLATE.format(title=args.title.replace('"', "'"), cls=cls, key=args.key), encoding="utf-8")
    print(f"created {target.relative_to(root)}")
    if not args.no_enable:
        project_file = root / "project.json"
        data = json.loads(project_file.read_text(encoding="utf-8")) if project_file.exists() else {}
        module = f"plugins.{args.key}"
        plugins = data.setdefault("plugins", [])
        if module not in plugins:
            plugins.append(module)
        pages = data.get("pages")
        if isinstance(pages, list) and args.key not in pages:
            index = pages.index("settings") if "settings" in pages else len(pages)
            pages.insert(index, args.key)
        project_file.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        print(f"enabled in {project_file.name}: plugins += {module}, pages += {args.key}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
